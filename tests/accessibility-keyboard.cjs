const { chromium } = require('playwright');
const assert = require('assert');
const fs = require('fs');

(async () => {
    const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
    const page = await browser.newPage();
    await require('./accessibility-browser.cjs')(page);
    const base = process.env.ACCESSIBILITY_BASE_URL || 'http://127.0.0.1:8099';
    const live = !['127.0.0.1', 'localhost', '[::1]'].includes(new URL(base).hostname);
    const reportPath = 'storage/app/accessibility/' + (live ? 'live-' : '') + 'keyboard-report.json';
    const checks = [];
    async function audit(label) {
        await page.addScriptTag({ path: require.resolve('axe-core/axe.min.js') });
        const violations = await page.evaluate(async () => (await axe.run(document, { runOnly: { type: 'tag', values: ['wcag2a','wcag2aa','wcag21aa','wcag22aa','best-practice'] } })).violations.map(v => ({ id: v.id, targets: v.nodes.map(n => n.target) })));
        checks.push({ label, violations });
        fs.writeFileSync(reportPath, JSON.stringify(checks, null, 2));
        if (violations.length) console.log(JSON.stringify(violations, null, 2));
        assert.deepStrictEqual(violations, [], label);
    }
    await page.goto(base + '/the-pool');
    await page.keyboard.press('Tab');
    assert.strictEqual(await page.locator('.skip-link').evaluate(el => el === document.activeElement), true);
    await page.keyboard.press('Enter');
    assert.strictEqual(await page.locator('#main-content').evaluate(el => el === document.activeElement), true);
    checks.push({ label: 'Skip link moves keyboard focus to main content', passed: true });
    const tile = page.locator('.gallery-grid-image').first();
    await tile.focus();
    await page.keyboard.press('Enter');
    assert.strictEqual(await page.locator('.glb-close').evaluate(el => el === document.activeElement), true);
    assert.ok(await page.locator('#glb-img').getAttribute('alt'));
    await page.keyboard.press('Shift+Tab');
    assert.strictEqual(await page.locator('.glb-next').evaluate(el => el === document.activeElement), true);
    await page.keyboard.press('Tab');
    assert.strictEqual(await page.locator('.glb-close').evaluate(el => el === document.activeElement), true);
    await page.keyboard.press('ArrowRight');
    assert.ok((await page.locator('#glb-counter').innerText()).startsWith('2'));
    await audit('Open gallery lightbox');
    await page.keyboard.press('Escape');
    assert.strictEqual(await tile.evaluate(el => el === document.activeElement), true);
    checks.push({ label: 'Gallery supports Enter, Tab wrapping, arrows, Escape and focus restoration', passed: true });

    await page.goto(base + '/');
    await page.locator('.hero-main').focus();
    await page.keyboard.press('Enter');
    await page.waitForTimeout(500);
    assert.strictEqual(await page.locator('#photoTourModal').evaluate(el => el.classList.contains('show')), true);
    await page.locator('.photo-tour-item img').first().focus();
    await page.keyboard.press(' ');
    assert.strictEqual(await page.locator('.lb-close').evaluate(el => el === document.activeElement), true);
    await audit('Nested home photo viewer');
    await page.keyboard.press('Escape');
    assert.strictEqual(await page.locator('.photo-tour-item img').first().evaluate(el => el === document.activeElement), true);
    assert.strictEqual(await page.locator('#photoTourModal').evaluate(el => el.classList.contains('show')), true);
    await page.keyboard.press('Escape');
    await page.waitForTimeout(500);
    assert.strictEqual(await page.locator('.hero-main').evaluate(el => el === document.activeElement), true);
    checks.push({ label: 'Nested photo viewer closes independently and restores both focus levels', passed: true });

    let quoteUrl = '';
    await page.route('**/api/price-quote?**', route => {
        quoteUrl = route.request().url();
        return route.fulfill({ contentType: 'application/json', body: '{"valid":false,"error":"Test dates unavailable"}' });
    });
    await page.locator('#accessible-checkin').fill('2026-11-20');
    await page.locator('#accessible-checkout').fill('2026-11-24');
    await page.locator('#accessible-dates-apply').focus();
    await page.keyboard.press('Enter');
    await page.waitForTimeout(300);
    assert.ok(quoteUrl.includes('checkin=2026-11-20&checkout=2026-11-24'));
    assert.strictEqual(await page.locator('#booking-book-now-btn').getAttribute('aria-disabled'), 'true');
    checks.push({ label: 'Native date inputs submit the same server availability checks', passed: true });

    await page.goto(base + '/book-now?checkin=2026-11-20&checkout=2026-11-24&guests=2');
    await page.locator('#bn-edit-dates-btn').focus();
    await page.keyboard.press('Enter');
    await page.waitForTimeout(100);
    assert.strictEqual(await page.locator('#bn-edit-dates-btn').getAttribute('aria-expanded'), 'true');
    assert.strictEqual(await page.locator('#bn-direct-checkin').evaluate(el => el === document.activeElement), true);
    await page.locator('#bn-direct-checkout').fill('2026-11-25');
    await page.waitForTimeout(100);
    assert.strictEqual(await page.locator('#bn-dates-apply-btn').isDisabled(), true);
    await page.route('**/api/price-quote?**', route => route.fulfill({ contentType: 'application/json', body: '{"valid":true}' }));
    await page.locator('#bn-direct-checkout').fill('2026-11-26');
    await page.waitForTimeout(100);
    assert.strictEqual(await page.locator('#bn-dates-apply-btn').isDisabled(), false);
    await audit('Booking date editor');
    await page.locator('#bn-dates-cancel-btn').focus();
    await page.keyboard.press('Enter');
    await page.waitForTimeout(100);
    assert.strictEqual(await page.locator('#bn-edit-dates-btn').evaluate(el => el === document.activeElement), true);
    assert.strictEqual(await page.locator('#bn-edit-dates-btn').getAttribute('aria-expanded'), 'false');
    checks.push({ label: 'Booking date editor announces expansion, validates dates and restores focus on cancel', passed: true });

    await page.setViewportSize({ width: 375, height: 812 });
    await page.goto(base + '/the-pool');
    await page.locator('.navbar-toggler').focus();
    await page.keyboard.press('Enter');
    await page.waitForTimeout(400);
    assert.strictEqual(await page.locator('.navbar-toggler').getAttribute('aria-expanded'), 'true');
    await page.locator('#navbarDropdownGallery').focus();
    await page.keyboard.press(' ');
    assert.strictEqual(await page.locator('#navbarDropdownGallery').getAttribute('aria-expanded'), 'true');
    await audit('Expanded mobile navigation');
    await page.screenshot({ path: 'storage/app/accessibility/' + (live ? 'live-' : '') + 'mobile-navigation.png' });
    checks.push({ label: 'Mobile navigation and dropdown open from the keyboard', passed: true });
    assert.strictEqual(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
    await page.emulateMedia({ reducedMotion: 'reduce' });
    await page.goto(base + '/about');
    assert.strictEqual(await page.locator('.carousel').evaluate(el => jQuery(el).data('bs.carousel')._interval), null);
    checks.push({ label: 'No automatic carousel motion', passed: true });
    fs.writeFileSync(reportPath, JSON.stringify(checks, null, 2));
    await browser.close();
    console.log(JSON.stringify(checks, null, 2));
})().catch(error => { console.error(error); process.exit(1); });
