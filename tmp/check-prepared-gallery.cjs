const {chromium}=require('../node_modules/playwright');
const fs=require('fs');
(async()=>{
 const browser=await chromium.launch({channel:'chrome',headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',error=>errors.push(error.message));
 await page.goto('file:///D:/laravel/villafab-laravel/docs/pinterest/prepared/index.html');
 await page.waitForSelector('.pin img');
 if(await page.locator('.pin').count()!==64)throw Error('Card count');
 await page.locator('#search').fill('075');
 if(await page.locator('.pin:visible').count()!==1)throw Error('ID filter');
 await page.locator('#search').fill('');
 await page.locator('#keyword').selectOption('luxury villa rental');
 if(await page.locator('.pin:visible').count()!==4)throw Error('Keyword filter');
 await page.locator('#location').selectOption('Los Angeles');
 if(await page.locator('.pin:visible').count()!==1)throw Error('Combined filter');
 await page.locator('#keyword').selectOption('');
 await page.locator('#location').selectOption('');
 const first=page.locator('.pin').first();
 await first.locator('summary').click();
 await first.locator('.copy-description').click();
 const copied=await first.locator('.copy-description').textContent();
 if(copied!=='Copied')throw Error('Copy description: '+copied);
 await first.locator('summary').click();
 await page.evaluate(()=>scrollTo(0,0));
 await page.screenshot({path:'tmp/prepared-gallery-desktop.png'});
 await page.setViewportSize({width:390,height:844});
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
 if(overflow)throw Error('Mobile horizontal overflow');
 await page.evaluate(()=>scrollTo(0,0));
 await page.screenshot({path:'tmp/prepared-gallery-mobile.png'});
 await browser.close();
 if(errors.length)throw Error(errors.join('\n'));
 const result={status:'passed',cards:64,search_filter:true,keyword_filter:true,combined_filters:true,copy_description:true,mobile_overflow:false,javascript_errors:errors};
 fs.writeFileSync('docs/pinterest/prepared/gallery-check.json',JSON.stringify(result,null,2)+'\n');
 console.log(JSON.stringify(result));
})().catch(e=>{console.error(e);process.exit(1)});
